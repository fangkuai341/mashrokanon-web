export function daysUntil(dateStr) {
  const diff = new Date(`${dateStr}T00:00:00`) - new Date()
  return Math.max(0, Math.ceil(diff / 86400000))
}

export function todayStr() {
  return new Date().toISOString().slice(0, 10)
}
